#!/usr/bin/env python3
"""Regenerate docs/TEST_RESULTS.md from committed results/*.json + COMPATIBILITY.md."""
from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
COMPAT = REPO / "docs" / "COMPATIBILITY.md"
OUT = REPO / "docs" / "TEST_RESULTS.md"
CPU_LLAMA_8B = 3.05

ARTIFACTS = [
    ("showcase_2026-11-23T2151Z.json", "Showcase bundle (metal + vLLM)"),
    ("showcase_tt_vs_cuda.json", "TT vs CUDA deck snippet"),
    ("tt_metal_b32_speed_2026-11-23T1309.json", "tt-metal batch-32 pytest"),
    ("vllm_offline_b32_speed_2026-11-23T1312.json", "vLLM offline (first full run)"),
    ("m4_native_compile_ab_Meta-Llama-3.1-8B-Instruct.json", "E4 compile A/B Llama-8B"),
    ("m4_native_compile_ab_SmolLM2-135M-Instruct.json", "E4 compile A/B SmolLM2-135M"),
]


def _load(name: str) -> dict | None:
    p = REPO / "results" / name
    if not p.is_file():
        return None
    return json.loads(p.read_text())


def _matrix_rows(md: str) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    in_table = False
    for line in md.splitlines():
        if line.startswith("| model |"):
            in_table = True
            continue
        if not in_table:
            continue
        if not line.startswith("|") or line.startswith("|---"):
            if rows:
                break
            continue
        parts = [c.strip() for c in line.strip("|").split("|")]
        if len(parts) < 10:
            continue
        rows.append(
            {
                "model": parts[0],
                "params": parts[1],
                "status": parts[3],
                "parity": parts[4],
                "tt_tok_s": parts[5].split()[0],
                "cpu_tok_s": parts[8].split()[0],
            }
        )
    return rows


def main() -> None:
    compat_md = COMPAT.read_text() if COMPAT.is_file() else ""
    matrix = _matrix_rows(compat_md)

    metal = _load("tt_metal_b32_speed_2026-11-23T1309.json") or {}
    vllm_name = "vllm_offline_b32_speed_2026-11-23T1312.json"
    vllm_runs = sorted((REPO / "results").glob("vllm_offline_b32_speed_*.json"))
    if vllm_runs:
        vllm_name = vllm_runs[-1].name
    vllm = _load(vllm_name) or {}
    serve_runs = sorted((REPO / "results").glob("vllm_serve_b32_speed_*.json"))
    serve_name = serve_runs[-1].name if serve_runs else ""
    serve = _load(serve_name) if serve_name else {}
    showcase_runs = sorted((REPO / "results").glob("showcase_*.json"))
    showcase_name = (
        "showcase_2026-11-23T2151Z.json"
        if (REPO / "results" / "showcase_2026-11-23T2151Z.json").is_file()
        else (showcase_runs[-1].name if showcase_runs else "")
    )
    showcase = _load(showcase_name) if showcase_name else {}

    llama_tt = next((r for r in matrix if "Llama-3.1-8B" in r["model"]), None)
    llama_tt_warm = float(llama_tt["tt_tok_s"]) if llama_tt else 11.09
    llama_cpu = float(llama_tt["cpu_tok_s"]) if llama_tt else CPU_LLAMA_8B

    metal_thr = float(
        showcase.get("headline_aggregate_tok_s")
        or metal.get("tok_s_throughput")
        or 1079.0
    )
    vllm_out = float(
        vllm.get("tqdm_output_tok_s_final")
        or vllm.get("engine_peak_generation_tok_s")
        or 909.0
    )

    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    lines = [
        "# Test results — speed vs compatibility (`tens`, P150)",
        "",
        f"*Generated by `scripts/render_test_results.py` — {ts}*",
        "",
        "This file is the **single index** for measured speed (native + TensCUDA) and",
        "model compatibility. Raw JSON lives in [`results/`](../results/). The full",
        "compatibility table is maintained in [COMPATIBILITY.md](COMPATIBILITY.md).",
        "",
        "## Executive summary (Llama-3.1-8B)",
        "",
        f"CPU greedy reference on this host: **~{llama_cpu} tok/s** (bf16 mmap, batch 1).",
        "",
        "| Stack | Role | Throughput | vs CPU | vs TensCUDA compile |",
        "|---|---|---:|---:|---:|",
        f"| CPU (matrix ref) | baseline | **{llama_cpu}** tok/s | 1× | — |",
        f"| **TensCUDA** (`import tenscuda`, compile default) | HF `.cuda()` compat | **{llama_tt_warm:.2f}** tok/s | **{llama_tt_warm/llama_cpu:.1f}×** | 1× |",
        f"| tt-metal batch-1 | native single-user | **~40** tok/s | **~13×** | **~3.6×** |",
        f"| **tt-metal batch-32** | native aggregate | **{metal_thr:.0f}** tok/s | **{metal_thr/llama_cpu:.0f}×** | **{metal_thr/llama_tt_warm:.0f}×** |",
        f"| **vLLM-TT offline** (32 seq) | serving-shaped | **{vllm_out:.0f}** tok/s | **{vllm_out/llama_cpu:.0f}×** | **{vllm_out/llama_tt_warm:.0f}×** |",
        "",
        "**Takeaway:** TensCUDA optimizes for *breadth* (many architectures, 32/32 parity).",
        "**Native metal / vLLM** optimizes for *throughput* (~100× faster than TensCUDA on 8B).",
        "",
        "```mermaid",
        "flowchart TB",
        "  subgraph compat [TensCUDA compat]",
        "    M135[SmolLM2 135M ~18 tok/s]",
        "    M8B[Llama 8B ~11 tok/s]",
        "  end",
        "  subgraph fast [Native fast path]",
        "    Metal[metal b32 ~1079 tok/s]",
        "    Vllm[vLLM ~909 tok/s]",
        "  end",
        "  CPU[CPU ~3 tok/s]",
        "  CPU --> compat",
        "  CPU --> fast",
        "```",
        "",
        "## Native speed tests (committed artifacts)",
        "",
        "| Test | Config | Key metric | Artifact |",
        "|---|---|---|---|",
    ]

    if metal:
        lines.append(
            f"| tt-metal `ttt_compat` | batch-32 performance | "
            f"**{metal.get('tok_s_throughput', '—')}** tok/s aggregate | "
            f"[`results/tt_metal_b32_speed_2026-11-23T1309.json`](../results/tt_metal_b32_speed_2026-11-23T1309.json) |"
        )
    if vllm:
        lines.append(
            f"| vLLM-TT offline | 256 prompts, b32, 128 new | "
            f"**{vllm.get('tqdm_output_tok_s_final', '—')}** / "
            f"peak **{vllm.get('engine_peak_generation_tok_s', '—')}** tok/s | "
            f"[`results/{vllm_name}`](../results/{vllm_name}) |"
        )
    if serve:
        lines.append(
            f"| vLLM-TT **serve** (`bench serve`) | 32 prompts, OpenAI backend | "
            f"**{serve.get('output_token_throughput_tok_s', '—')}** tok/s | "
            f"[`results/{serve_name}`](../results/{serve_name}) |"
        )
    listed = {"tt_metal_b32_speed_2026-11-23T1309.json", vllm_name}
    for name, desc in ARTIFACTS:
        if name in listed:
            continue
        if _load(name):
            lines.append(
                f"| {desc} | — | see JSON | [`results/{name}`](../results/{name}) |"
            )

    lines.extend(
        [
            "",
            "Reproduce: [CUDA_TO_METAL.md](CUDA_TO_METAL.md), [SPEED.md](SPEED.md),",
            "`bash scripts/run_fast_aggregate_measure.sh` or",
            "`run_tt_speed_showcase.sh --skip-metal` after metal if `EngineDeadError`.",
            "",
            "## TensCUDA compatibility matrix (warm tok/s vs CPU)",
            "",
            "All rows: greedy 32 new tokens, batch 1, streaming load, parity vs CPU reference.",
            "Regenerate table: `python scripts/matrix.py --render`.",
            "",
            "| Model | Params | Status | Parity | TT tok/s | CPU tok/s | TT/CPU |",
            "|---|---|---|---|---:|---:|---:|",
        ]
    )

    for r in matrix:
        try:
            tt = float(r["tt_tok_s"])
            cpu = float(r["cpu_tok_s"])
            ratio = f"{tt/cpu:.2f}×" if cpu > 0 else "—"
        except ValueError:
            ratio = "—"
        short = r["model"].split("/")[-1]
        parity_short = r["parity"].split(";")[0].strip()
        lines.append(
            f"| {short} | {r['params']} | {r['status']} | {parity_short} | "
            f"{r['tt_tok_s']} | {r['cpu_tok_s']} | {ratio} |"
        )

    lines.extend(
        [
            "",
            "### Compatibility vs speed (patterns)",
            "",
            "- **Small models (≤1.7B):** often **TT &lt; CPU** on this host-bound TT-XLA path",
            "  (e.g. SmolLM2-135M **18 vs 38 CPU tok/s**). Compat wins, not speed.",
            "- **3B–8B:** TT **beats CPU** (~3–4× on 8B compile) but stays **~100× below**",
            "  native batch-32 serving.",
            "- **Near-tie parity:** Qwen2.5-0.5B, Phi-3.5-mini, Mistral-7B — see notes in",
            "  [COMPATIBILITY.md](COMPATIBILITY.md); not speed regressions.",
            "",
            "## TensCUDA native-op experiment (M4 E4)",
            "",
            "`TENSCUDA_NATIVE_OPS=sdpa,rms_norm` vs compile-only — **32/32** tokens, **no** decode win:",
            "",
            "| Model | compile ms | + native ms |",
            "|---|---:|---:|",
        ]
    )

    for name, label in (
        ("m4_native_compile_ab_SmolLM2-135M-Instruct.json", "SmolLM2-135M"),
        ("m4_native_compile_ab_Meta-Llama-3.1-8B-Instruct.json", "Llama-3.1-8B"),
    ):
        doc = _load(name)
        if not doc:
            continue
        c = doc["rows"]["compile"]["warm_ms"]
        n = doc["rows"]["compile_native"]["warm_ms"]
        lines.append(f"| {label} | {c} | {n} |")

    lines.extend(
        [
            "",
            "## `results/` speed artifact index",
            "",
            "| File | Kind |",
            "|---|---|",
        ]
    )
    for name, desc in ARTIFACTS + [
        ("vllm_offline_b32_tens_2026-11-23.json", "Hand-recorded vLLM summary"),
    ]:
        if (REPO / "results" / name).is_file():
            lines.append(f"| `{name}` | {desc} |")

    # Pick up any vllm_offline_b32_speed_* newer than 1312
    for p in sorted((REPO / "results").glob("vllm_offline_b32_speed_*.json")):
        if p.name in {
            "vllm_offline_b32_speed_2026-11-23T1312.json",
        }:
            continue
        lines.append(f"| `{p.name}` | vLLM offline (additional run) |")
    for p in sorted((REPO / "results").glob("vllm_serve_b32_speed_*.json")):
        lines.append(f"| `{p.name}` | vLLM serve bench |")

    OUT.write_text("\n".join(lines) + "\n")
    print(OUT)


if __name__ == "__main__":
    main()