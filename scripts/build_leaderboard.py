"""Build docs/LEADERBOARD.md from benchmarks/results/*.json (tenscuda-bench/1 results).

    python scripts/build_leaderboard.py [--check]

Rows are grouped by model and sorted by warm decode tok/s (fastest first). --check only
validates the result files (useful in a PR) and exits non-zero on a bad file.
"""
import argparse
import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCHEMAS = {"tenscuda-bench/1"}
REQUIRED = [("schema",), ("date",), ("workload", "model"), ("workload", "mode"), ("results", "warm_tok_per_s"),
            ("results", "parity", "status"), ("config", "cards")]
LEAK = re.compile(r"(/home/|/Users/|\b(?:\d{1,3}\.){3}\d{1,3}\b)")


def get(d, path):
    for k in path:
        d = d[k]
    return d


def validate(path, d):
    errs = []
    if d.get("schema") not in SCHEMAS:
        errs.append(f"unknown schema {d.get('schema')!r}")
    for p in REQUIRED:
        try:
            get(d, p)
        except (KeyError, TypeError, IndexError):
            errs.append("missing " + ".".join(p))
    text = json.dumps({k: v for k, v in d.items() if k != "config"}) + json.dumps(d.get("config", {}).get("host", {}))
    if LEAK.search(text):
        errs.append("looks like it contains a path or IP address; re-run the scrubbed `python -m tenscuda bench`")
    return [f"{os.path.relpath(path, ROOT)}: {e}" for e in errs]


def row(d):
    r, w, c = d["results"], d["workload"], d["config"]
    cards = c.get("cards") or [{}]
    sw, host = c.get("software", {}), c.get("host", {})
    tel = r.get("telemetry") or {}
    p = r["parity"]
    par = p["status"]
    if "matching_prefix" in p:
        par += f" ({p['matching_prefix']}/{p['total']})"
    return [w["model"], w["mode"], f"{r['warm_tok_per_s']:.2f}", f"{r['first_run_s']:.0f}", par,
            f"{c.get('card_count', len(cards))}x {cards[0].get('type', '?')}", cards[0].get("fw_bundle") or "?",
            c.get("kmd") or "?", sw.get("pjrt_plugin_tt") or "?", sw.get("tenscuda_commit") or sw.get("tenscuda") or "?",
            (host.get("cpu") or "?").replace("|", "/"), f"{host.get('ram_gib', '?')} GiB",
            f"{r.get('peak_host_rss_gib', '?')} GiB",
            f"{tel.get('temp_c_max', '-')} C / {tel.get('power_w_mean', '-')} W" if tel else "-", d["date"][:10]]


COLS = ["model", "mode", "warm tok/s", "first run s", "CPU parity", "card", "firmware", "KMD", "pjrt-plugin-tt",
        "tenscuda", "host CPU", "host RAM", "peak RSS", "max temp / mean power", "date"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    files = sorted(glob.glob(os.path.join(ROOT, "benchmarks", "results", "*.json")))
    data, errs = [], []
    for f in files:
        try:
            d = json.load(open(f))
        except Exception as e:
            errs.append(f"{os.path.relpath(f, ROOT)}: not valid JSON ({e})")
            continue
        e = validate(f, d)
        errs += e
        if not e:
            data.append(d)
    for e in errs:
        print("ERROR", e, file=sys.stderr)
    if a.check:
        print(f"{len(data)} valid, {len(errs)} errors")
        return 1 if errs else 0
    data.sort(key=lambda d: (d["workload"]["model"].lower(), d["workload"]["mode"], -d["results"]["warm_tok_per_s"]))
    out = ["# TensCUDA community benchmark leaderboard", "",
           "Generated by `python scripts/build_leaderboard.py` from `benchmarks/results/*.json`. Don't edit it by hand.",
           "Each row is one `python -m tenscuda bench` run: fixed prompt, greedy, seed 0, batch 1, bf16 weights,",
           "32 new tokens (`full`) or 16 (`quick`). **warm tok/s** is decode speed after compilation. **first run s**",
           "includes TT-MLIR compilation. **CPU parity** compares tokens with a CPU run of the same prompt.",
           "Results are self-reported and not independently verified.", "",
           "To add yours, see [Benchmark your card](../README.md#benchmark-your-card).", "",
           "| " + " | ".join(COLS) + " |", "|" + "---|" * len(COLS)]
    out += ["| " + " | ".join(str(x) for x in row(d)) + " |" for d in data]
    if not data:
        out.append("| _no results yet_ |" + " |" * (len(COLS) - 1))
    open(os.path.join(ROOT, "docs", "LEADERBOARD.md"), "w").write("\n".join(out) + "\n")
    print(f"docs/LEADERBOARD.md: {len(data)} results")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
